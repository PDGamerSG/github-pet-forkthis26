const axios = require("axios");

async function getGitHubUser(username) {
    const response = await axios.get(
        `https://api.github.com/users/${username}`
    );

    return response.data;
}

/**
 * Fetches public activity events for a GitHub user across available pages.
 */
async function getGitHubEvents(username) {
    const allEvents =[];
    for(let page =1;page<= 3;page++) {
        const response = await axios.get(
            `https://api.github.com/users/${username}/events/public?per_page=100&page=${page}`
        );
        if(!Array.isArray(response.data) || response.data.length === 0){
            break;
        }
        allEvents.push(...response.data);
    }
    return allEvents;
}


/**
 * Checks if a repository is accessible.
 * Used for verifying repository availability.
 */
async function checkRepoAccessible(repoName, token) {
    try {
        const headers = token ? { Authorization: `Bearer ${token}` } : {};
        const response = await axios.get(`https://api.github.com/repos/${repoName}`, { headers });
        return response.status === 200;
    } catch (error) {
        // If 404 or 403 or network error, considered deleted/inaccessible
        return false;
    }
}

module.exports = {
    getGitHubUser,
    getGitHubEvents,
    checkRepoAccessible
};






























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































